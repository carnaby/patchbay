import { type ClockConfig, clockModel, clockSvg, describeClock, THEMES } from '@patchbay/core';
import { useEffect, useMemo, useState } from 'react';
import { useTheme } from '../lib/hooks.ts';

/** Re-renders on every second (or minute) boundary, and at once when a hidden tab becomes visible again. */
function useNow(stepMs: number) {
  const [now, setNow] = useState(() => Date.now());
  useEffect(() => {
    let timer: ReturnType<typeof setTimeout>;
    const tick = () => {
      const t = Date.now();
      setNow(t);
      // Aligned to the boundary, so the display never lags the real second by a random fraction.
      timer = setTimeout(tick, stepMs - (t % stepMs) + 5);
    };
    tick();
    // Browsers throttle timers in hidden tabs; a wall screen that comes back must not show a stale time.
    const onVisible = () => {
      if (document.visibilityState !== 'visible') return;
      clearTimeout(timer);
      tick();
    };
    document.addEventListener('visibilitychange', onVisible);
    return () => {
      clearTimeout(timer);
      document.removeEventListener('visibilitychange', onVisible);
    };
  }, [stepMs]);
  return now;
}

export function ClockBody({ config }: { config: ClockConfig }) {
  const mode = useTheme();
  const needsSeconds = config.showSeconds;
  const now = useNow(needsSeconds ? 1000 : 60_000);
  const locale = typeof navigator === 'undefined' ? 'en-GB' : navigator.language;
  const model = useMemo(() => clockModel(config, now, { locale }), [config, now, locale]);
  // The SVG is generated by core from numbers, the formatted date and the escaped label: no untrusted markup.
  const svg = useMemo(() => clockSvg(model, config, THEMES[mode]), [model, config, mode]);
  // Announced once a minute at most: the label leaves out the seconds.
  const label = describeClock(model);
  return (
    <div
      role="img"
      aria-label={label}
      title={label}
      className="flex h-full w-full items-center justify-center [&>svg]:max-h-full [&>svg]:max-w-full"
      // biome-ignore lint/security/noDangerouslySetInnerHtml: core builds this SVG and escapes every text in it
      dangerouslySetInnerHTML={{ __html: svg }}
    />
  );
}
